#!/usr/bin/env python3
"""Regenerate examples/companion_radio/CompanionOtaCerts.h.

The DMC companion verifies the OTA server's TLS certificate against this short
list of roots instead of a full CA bundle (a few KB of flash instead of ~60 KB).
ota.dutchmeshcore.nl sits behind Cloudflare, whose edge certificates come from
Google Trust Services, Let's Encrypt or SSL.com, so the roots of those three are
enough. Add a root here if Cloudflare starts using another CA.

Roots are taken from the Mozilla store as shipped by certifi:
  pip install certifi && python3 scripts/gen_companion_ota_certs.py
"""
import re
import sys
from pathlib import Path

import certifi

ROOTS = [
    "GTS Root R1",
    "GTS Root R2",
    "GTS Root R3",
    "GTS Root R4",
    "ISRG Root X1",
    "ISRG Root X2",
    "SSL.com TLS RSA Root CA 2022",
    "SSL.com TLS ECC Root CA 2022",
    "SSL.com Root Certification Authority RSA",
    "SSL.com Root Certification Authority ECC",
]

OUT = Path(__file__).resolve().parent.parent / "examples" / "companion_radio" / "CompanionOtaCerts.h"


def main() -> int:
    text = Path(certifi.where()).read_text(encoding="utf-8")
    blocks = {}
    for m in re.finditer(r'# Label: "([^"]+)"\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----)', text, re.S):
        blocks[m.group(1)] = m.group(2)
    missing = [r for r in ROOTS if r not in blocks]
    if missing:
        print("not in the certifi store: " + ", ".join(missing), file=sys.stderr)
        return 1

    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/gen_companion_ota_certs.py from the Mozilla root store",
        "// (certifi " + certifi.__version__ + "). Do not edit by hand.",
        "//",
        "// Roots the companion trusts for the OTA download from ota.dutchmeshcore.nl",
        "// (Cloudflare: Google Trust Services, Let's Encrypt, SSL.com).",
        "",
        "static const char COMPANION_OTA_ROOT_CERTS[] =",
    ]
    for name in ROOTS:
        lines.append("  // " + name)
        for pem_line in blocks[name].splitlines():
            lines.append('  "' + pem_line + '\\n"')
    lines[-1] += ";"
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote " + str(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
